X("charcoal-at-camp","""
## Charcoal in wind and cold

Wind feeds coals oxygen, so they burn hotter and faster; shelter the grill behind a vehicle or rock outcrop and add coals more often. In cold, damp weather, charcoal takes longer to light and holds less heat, so start earlier and use a little more. On hot, calm days, you may need less than you'd expect. Learning how your grill behaves in different conditions is part of becoming a confident camp cook.
""")
X("sleeping-warm-at-camp","""
## Layering for sleep

Instead of sleeping in a bulky jacket, which can compress and restrict circulation, wear a base layer of thermal top and bottoms, warm socks and a hat. If you're still cold, drape the jacket over the top of the sleeping bag where it adds insulation without being crushed. Keep tomorrow's clothes inside the bag's foot box so they're warm when you dress in the morning.
""")
